def get_grantham_distance(aa1: str, aa2: str) -> float:
    a1, a2 = aa1.upper(), aa2.upper()
    if a1 == a2:
        return 0.0
    if a1 == '*' or a2 == '*':
        return 215.0  # Maximum disruption for nonsense / stop codon
    return float(GRANTHAM_DISTANCES.get((a1, a2), GRANTHAM_DISTANCES.get((a2, a1), 100.0)))

def get_blosum62_score(aa1: str, aa2: str) -> float:
    a1, a2 = aa1.upper(), aa2.upper()
    if a1 == '*' or a2 == '*':
        return -4.0
    return float(BLOSUM62.get((a1, a2), BLOSUM62.get((a2, a1), -2.0)))

def extract_ml_features(
    orig_aa: str,
    mod_aa: str,
    codon_position: int,
    relative_position: float,
    local_gc_content: float,
    is_transition: bool
) -> dict:
    """
    Extract standardized feature vector for ML model inference.
    """
    a1 = orig_aa.upper()
    a2 = mod_aa.upper()
    
    grantham = get_grantham_distance(a1, a2)
    blosum = get_blosum62_score(a1, a2)
    
    p1 = AA_PROPERTIES.get(a1, (120.0, 6.0, 0.0, 0))
    p2 = AA_PROPERTIES.get(a2, (120.0, 6.0, 0.0, 0))
    
    delta_mw = abs(p2[0] - p1[0])
    delta_pi = abs(p2[1] - p1[1])
    delta_hydro = abs(p2[2] - p1[2])
    charge_change = abs(p2[3] - p1[3])
    
    return {
        "grantham_distance": grantham,
        "blosum62_score": blosum,
        "delta_molecular_weight": delta_mw,
        "delta_isoelectric_point": delta_pi,
        "delta_hydropathy": delta_hydro,
        "charge_change": float(charge_change),
        "codon_position": float(codon_position),
        "relative_position": float(relative_position),
        "local_gc_content": float(local_gc_content),
        "is_transition": 1.0 if is_transition else 0.0
    }
